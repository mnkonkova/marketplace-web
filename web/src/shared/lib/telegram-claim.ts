/**
 * Билет привязки телеграма, приехавший в адресе.
 *
 * Мини-апп не регистрирует человека сам: анкета с категориями и
 * портфолио заполняется на сайте. Но возвращать его после регистрации
 * в бот «нажать ещё раз» нельзя — он уже получил, зачем приходил, и
 * половина не вернётся. Поэтому мини-апп выдаёт билет, кладёт его в
 * адрес анкеты, а браузер гасит сразу, как только появилась сессия.
 *
 * Хранится в sessionStorage, а не в памяти: между «открыл анкету» и
 * «завёл аккаунт» человек перезагружает страницу, уходит читать почту
 * и возвращается. Вкладку закрыл — билет пропал, и это правильно:
 * привязывать телеграм к аккаунту, заведённому через час в другом
 * месте, мы не хотим.
 */
const KEY = 'prmarket.tg.claim';

/** Снять билет из адреса и запомнить. Зовётся один раз при старте. */
export function captureTelegramTicket(): void {
  try {
    const code = new URLSearchParams(window.location.search).get('tg');
    if (code) sessionStorage.setItem(KEY, code);
  } catch {
    // Приватное окно без хранилища: привязка просто не случится
    // сама — человек сделает её кнопкой в проекте.
  }
}

export function pendingTelegramTicket(): string {
  try {
    return sessionStorage.getItem(KEY) ?? '';
  } catch {
    return '';
  }
}

export function clearTelegramTicket(): void {
  try {
    sessionStorage.removeItem(KEY);
  } catch {
    /* см. выше */
  }
}
