/**
 * Дописать схему к ссылке, которую вставили без неё.
 *
 * Люди копируют адрес из строки браузера, а он давно показывает
 * «vk.com/wall-1_2» без «https://». Отказ «ссылка должна начинаться с
 * http://» на таком адресе — это требование к человеку сделать работу,
 * которую машина делает сама и без ошибок.
 *
 * Дописываем https, а не http: сегодня это молчаливое умолчание сети, а
 * http означал бы «открыто по незащищённому» там, где никто этого не
 * просил.
 *
 * Возвращаем введённое, а не разобранный URL: строка уходит в хранилище и
 * оттуда же показывается менеджеру текстом ссылки. u.toString() превратил
 * бы «пример.рф/?utm_source=vk» в «xn--e1afmkfd.xn--p1ai/?utm_source=vk»,
 * и человек перестал бы узнавать в списке метку, которую сам и завёл.
 * Разобранный URL нужен только чтобы проверить адрес, а хранится и
 * показывается то, что набрали, — плюс схема, если её не было.
 *
 * null — это не ссылка вовсе. Отказ по трём поводам, и каждый про то, что
 * человек увидит не тот адрес, на который попадёт:
 *
 *  - userinfo. «vk.com@evil.com/path» — это evil.com, а начинается текстом
 *    «vk.com». В UTM-метках ссылка рисуется текстом самого адреса, в
 *    материалах текстом служит название и хоста не видно вовсе;
 *  - начало со слэша или обратного слэша. «//evil.com», «\\evil.com»,
 *    «/\evil.com» выглядят как путь внутри нашего же сайта, а после
 *    дописывания схемы ведут на чужой хост;
 *  - имя узла не из непустых меток через точку. «vkcom» — опечатка,
 *    «.», «..», «.a», «a.» — мусор, который разборщик URL пропускает.
 *
 * Пробел внутри отказом не считается: адрес с пробелом в пути или в
 * значении метки («…/бриф на май.pdf», «?utm_campaign=Тест два») —
 * обычное дело, браузер его кодирует сам, и бэк на нём не спотыкается.
 * Пробел в имени узла отсечёт правило про имя узла. Управляющие символы —
 * отказ: их разборщик молча выбрасывает, и проверенный адрес разошёлся
 * бы с сохранённым.
 */
export function withScheme(raw: string): string | null {
  const value = raw.trim();
  if (!value) return null;
  // Табуляции и переводы строки разборщик URL выкидывает из середины
  // адреса: «ev\nil.com» он читает как «evil.com». Проверили бы одно,
  // сохранили другое — поэтому отказ.
  // eslint-disable-next-line no-control-regex
  if (/[\u0000-\u001f\u007f]/.test(value)) return null;
  if (/^[/\\]/.test(value)) return null;

  const candidate = /^[a-z][a-z0-9+.-]*:\/\//i.test(value) ? value : `https://${value}`;
  let u: URL;
  try {
    u = new URL(candidate);
  } catch {
    return null;
  }
  if (u.protocol !== 'http:' && u.protocol !== 'https:') return null;
  if (u.username || u.password) return null;
  if (!isHostLike(u.hostname)) return null;
  return candidate;
}

/**
 * Имя узла — непустые метки из букв, цифр и дефисов через точку.
 *
 * Правило ловит опечатки («vkcom») и мусор, который разборщик URL
 * пропускает («.», «..», «.a», «a.»). IDN сюда приходит уже в punycode
 * («пример.рф» → «xn--e1afmkfd.xn--p1ai»), так что латиницы хватает.
 *
 * Набор символов перечислен явно, а не отдан разборщику, потому что
 * разборщики расходятся: «vk.com evil.com» Chrome принимает, подставляя
 * «vk.com%20evil.com», а Node на том же адресе бросает исключение.
 * Проверка, которая в браузере и в тестах на ноде отвечает по-разному, —
 * это проверка, которой нельзя верить ни там, ни там.
 *
 * Литерал адреса — и IPv4 «1.2.3.4», и IPv6 «[::1]» — принимаем. Точка в
 * имени нужна не сама по себе: она отличает адрес от опечатки. Литерал
 * набирают намеренно, опечаткой он не бывает, и IPv4 здесь проходил
 * всегда — отклонять IPv6 значило бы запрещать одно и то же в двух
 * записях. Ссылка на 192.168.x.x заказчику бесполезна, но это выбор
 * менеджера, а не ошибка ввода, и ловить его здесь нечем.
 */
function isHostLike(hostname: string): boolean {
  // Скобки вокруг IPv6 ставит сам разборщик, и внутрь он пускает только
  // разобранный литерал — здесь остаётся сверить набор символов.
  if (hostname.startsWith('[')) return /^\[[0-9a-f:.]+\]$/i.test(hostname);
  return /^[a-z0-9_-]+(\.[a-z0-9_-]+)+$/i.test(hostname);
}
