/**
 * Тач-экран определяем один раз при создании компонента: на телефоне списки
 * открываются нижней шторкой, а выпадающие меню ng-zorro у края экрана
 * прижимаются к границе и половина пунктов уезжает под палец.
 *
 * Проверяем именно (hover: none) и (pointer: coarse), а не ширину: у
 * ноутбуков с тачскрином ширина десктопная, но hover есть — им шторка не
 * нужна.
 */
export function isTouchDevice(): boolean {
  return (
    typeof window !== 'undefined' &&
    typeof window.matchMedia === 'function' &&
    window.matchMedia('(hover: none) and (pointer: coarse)').matches
  );
}

/**
 * Ширина, ниже которой окно по центру перестаёт быть окном.
 *
 * Та же граница, что у вёрстки ($touch в _breakpoints.scss): окно
 * ng-zorro шириной 520 px в экран 390 px не помещается ни при каком
 * устройстве ввода.
 */
const SHEET_MAX_WIDTH = 720;

/**
 * Показывать диалог нижней шторкой, а не окном по центру.
 *
 * Не то же самое, что isTouchDevice(). Тач — про устройство ввода: им
 * решают, нужна ли вибрация, можно ли навести курсор, стоит ли ловить
 * смахивание. А это — про место на экране, и решается оно шириной
 * тоже.
 *
 * Разница вылезла на живом: узкое окно настольного браузера тачем не
 * считается, и «Создать проект» открывался окном на 520 px в экране
 * 390 px. Экранная клавиатура такому окну добивает остальное — оно
 * центрируется по тому, что осталось видимым, и прыгает на каждом
 * переходе между полями.
 */
export function prefersSheet(): boolean {
  if (isTouchDevice()) return true;
  return typeof window !== 'undefined' && window.innerWidth <= SHEET_MAX_WIDTH;
}
