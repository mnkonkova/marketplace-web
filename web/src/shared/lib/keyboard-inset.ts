/**
 * Сколько экрана занимает экранная клавиатура — числом в CSS.
 *
 * Зачем это вообще. Нижняя шторка прибита к НИЗУ СТРАНИЦЫ (position:
 * fixed), а клавиатура в мобильных браузерах страницу не двигает: она
 * уменьшает «видимую область» (visualViewport) и накрывает собой
 * нижнюю часть окна. Для шторки ничего не изменилось — она осталась
 * внизу, под клавиатурой. Браузер, спасая положение, подкручивает
 * страницу к полю ввода сам, каждый раз по-своему; на переходе между
 * полями подкручивает заново. Со стороны это выглядит ровно так, как
 * сказала владелец продукта: «форма скачет от клавиатуры».
 *
 * Починить это в CSS нельзя: высоты клавиатуры там нет. Зато её можно
 * посчитать — разница между окном и видимой областью — и положить в
 * переменную, которой CSS уже распорядится сам (styles.scss,
 * .ant-drawer-bottom). Одно число, один слушатель на приложение, и ни
 * одного `scrollIntoView` по таймеру.
 *
 * Считаем от НИЗА: клавиатура приходит снизу, а сверху над видимой
 * областью бывает свёрнутая адресная строка — её вычитать не нужно.
 */

/** Ниже этого считаем, что клавиатуры нет: адресная строка, и только. */
const NOISE_PX = 80;

export function trackKeyboardInset(): void {
  const vv = window.visualViewport;
  if (!vv) {
    // Старый браузер без visualViewport: переменная останется нулём, и
    // всё работает как раньше. Хуже не делаем.
    return;
  }

  let last = -1;
  const apply = (): void => {
    // offsetTop — насколько видимая область смещена вниз (страница
    // подкручена браузером). Нижний зазор = окно − видимое − смещение.
    const gap = window.innerHeight - vv.height - vv.offsetTop;
    const inset = gap > NOISE_PX ? Math.round(gap) : 0;
    if (inset === last) return;
    last = inset;
    document.documentElement.style.setProperty('--kb-inset', `${inset}px`);
    // Класс — для правил, которым мало отступа: например, шторка при
    // поднятой клавиатуре не должна занимать 88% экрана.
    document.documentElement.classList.toggle('kb-up', inset > 0);
  };

  apply();
  vv.addEventListener('resize', apply);
  vv.addEventListener('scroll', apply);
}
