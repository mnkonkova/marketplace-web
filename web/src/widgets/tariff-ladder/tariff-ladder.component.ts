import { ChangeDetectionStrategy, Component, computed, input } from '@angular/core';
import { CommonModule } from '@angular/common';

import { formatMoney } from '@entities/billing/lib/money';
import type { OverviewTariff } from '@entities/billing/model/billing.types';

/**
 * Тарифная лесенка: почему тысяча просмотров стоит столько, сколько
 * написано рядом.
 *
 * Главный коммерческий аргумент продукта, и до этого экрана его на экране
 * не было вовсе: стоял результат формулы — «56 ₽ за тысячу» — и ни слова
 * о самой формуле. Прочитать это можно было только как «повезло», хотя
 * так устроен договор: первые просмотры КАЖДОГО ролика идут по стартовой
 * ставке, всё, что ролик набрал сверх, — по пониженной, и чем дальше он
 * расходится, тем ниже выходит средняя цена тысячи.
 *
 * Порог — на ролик, а не на проект. Разница не в формулировке: у пяти
 * роликов по 400 000 сверхпорогового объёма нет вовсе, и лесенка,
 * обещающая «первый миллион проекта», описывала бы чужое правило.
 *
 * Один компонент на оба экрана — сводку и карточку проекта. Разметка
 * лесенки жила в двух местах ровно один час и за этот час успела
 * разойтись подписями; две копии главного аргумента продукта — это две
 * версии того, как устроен договор.
 *
 * НИЧЕГО НЕ СЧИТАЕТ. Ставки, пороги и суммы приходят с сервера готовыми,
 * и приходят только тогда, когда разложение сходится с ценой тысячи
 * рядом (см. tariffLadder.result в internal/billing). Вторая реализация
 * ступеней в браузере разошлась бы со счётом молча — заметили бы это в
 * день оплаты.
 */
@Component({
  selector: 'app-tariff-ladder',
  standalone: true,
  imports: [CommonModule],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './tariff-ladder.component.html',
  styleUrl: './tariff-ladder.component.scss',
})
export class TariffLadderComponent {
  public readonly tariff = input.required<OverviewTariff>();

  /**
   * Подпись под итогом: почему сумма такая и изменится ли она.
   *
   * Приходит снаружи, потому что зависит от экрана: в сводке это деление
   * «168 000 ₽ ÷ 3 000 тысяч = 56 ₽», в карточке проекта — «период
   * открыт, сумма ещё вырастет». Пустая — строки нет вовсе.
   */
  public readonly note = input('');

  /**
   * Цена тысячи готовой строкой — её показывает подпись деления.
   *
   * Именно готовой: делить здесь значило бы посчитать деньги в браузере.
   * Пусто — деления в подписи не будет.
   */
  public readonly costPer1000 = input<number | null>(null);

  /** Заголовок над лесенкой. Пустой — лесенка стоит без него. */
  public readonly heading = input('');

  public readonly money = formatMoney;

  /**
   * Делитель подписи: «÷ 3 000 тысяч просмотров».
   *
   * Тысячи, а не просмотры: иначе на экране стоит деление на 3 000 000 с
   * результатом 56, и оно не сходится — а это первое, что проверяют
   * калькулятором.
   */
  public readonly thousands = computed(() =>
    Math.round(this.tariff().views / 1000).toLocaleString('ru-RU'),
  );
}
