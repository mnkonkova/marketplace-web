/**
 * Название проекта так, как оно называется ДЛЯ ЗАКАЗЧИКА.
 *
 * В базе у проектов заводятся служебные пометки конвейера — «(e2e)»,
 * «(тест)», «(копия)». Они наши, а не его: кабинет показывают начальству
 * и вставляют в коммерческое предложение, и «PetFlat · UGC (e2e)» в
 * заголовке читается как недоделка, а «(копия)» — как ошибка менеджера.
 *
 * Режем ТОЛЬКО скобки в самом конце и только со служебным словом внутри.
 * «Корм для кошек (вертикальные ролики)» — часть названия, и трогать её
 * нельзя: обрезав её, мы соврём сильнее, чем оставив пометку.
 *
 * Чистит только показ. В базе название остаётся как есть: по нему
 * менеджер находит проект, и переименовывать чужие записи ради вида
 * чужого экрана нельзя.
 *
 * Одна функция на все места, где это название показывают заказчику:
 * реестр проектов и шапка карточки. Две копии регулярного выражения
 * разошлись бы на первой же новой пометке, и суффикс остался бы ровно в
 * одном из двух мест — том, куда не заглянули.
 */
const SERVICE_SUFFIX = /\s*\((?:e2e|test|тест|копия|demo|черновик)\)\s*$/i;

export function clientTitle(title: string | null | undefined): string {
  return (title ?? '').replace(SERVICE_SUFFIX, '').trim();
}
