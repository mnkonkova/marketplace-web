/**
 * Почему по ссылке нет цифр — человеческой строкой.
 *
 * Сборщик отвечает по-своему и по-разному: «Метрики отдельных постов
 * для 'vk' пока не поддержаны», «Likee: ролик не найден или недоступен
 * из этой сети», «ScrapeCreators 404: Account doesn't exist». Показывать
 * это как есть нельзя — человек читает кабинет, а не наш лог. Но и
 * выбрасывать нельзя: ровно из-за выброшенной причины ноль в отчёте
 * целый день выглядел как «ролик никто не смотрит».
 *
 * Поэтому здесь — короткая подпись для глаз, а исходный текст уезжает в
 * подсказку: когда формулировка на той стороне поменяется, подпись
 * станет общей, но точный ответ останется виден.
 */
export function collectErrorLabel(raw?: string): string {
  const text = (raw ?? '').trim().toLowerCase();
  if (!text) return '';
  if (text.includes('не поддерж')) return 'площадка не собирается';
  if (
    text.includes('не найден') ||
    text.includes('удален') ||
    text.includes('удалён') ||
    text.includes("doesn't exist") ||
    text.includes('404')
  ) {
    return 'ролик не найден';
  }
  if (text.includes('недоступ') || text.includes('закрыт') || text.includes('приватн')) {
    return 'ролик закрыт';
  }
  if (text.includes('кредит') || text.includes('credit') || text.includes('limit')) {
    return 'кончились запросы к сборщику';
  }
  return 'сбор не прошёл';
}
