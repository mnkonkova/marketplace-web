import type { Publication } from '../model/publication.types';

/**
 * Выкладка, которую креатор завёл себе сам.
 *
 * Зачем она вообще: план периода ставит менеджер, и когда план выполнен,
 * а до ступени не хватает просмотров, добрать человеку нечем — дат
 * впереди нет. Самодобавленный ролик и есть эта возможность.
 *
 * Правило, без которого кнопку никто не нажмёт: такой ролик НЕ входит в
 * знаменатель недосдачи. Оклад считается только по тому, что поставил
 * менеджер, — добавить и не сдать не штрафуется. Просмотры при этом
 * идут в период и в ступени наравне с плановыми. Правило живёт на
 * сервере; здесь оно только называется словами на экране.
 *
 * Дата на клиенте проверяется дважды не из недоверия к серверу: пикер
 * должен закрыть неверные дни ДО клика, иначе человек выбирает день,
 * жмёт «Добавить» и получает отказ — про день, который ему показали
 * как доступный.
 */

/** Сколько дней вперёд разрешено. Дальше — опечатка в годе, а не план. */
export const MAX_AHEAD_DAYS = 365;

/**
 * Локальная дата в ГГГГ-ММ-ДД.
 *
 * Именно локальная: toISOString() переводит в UTC, и восточнее Гринвича
 * выбранное «20 сентября» уезжает на 19-е — человек видит в календаре
 * один день, а заводится другой.
 */
export function ymdLocal(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

/** Полночь того же дня — чтобы сравнивать дни, а не моменты. */
function startOfDay(d: Date): number {
  const copy = new Date(d);
  copy.setHours(0, 0, 0, 0);
  return copy.getTime();
}

/** День раньше сегодняшнего. Сегодня — можно: ролик мог выйти утром. */
export function isPastDay(day: Date, now: Date = new Date()): boolean {
  return startOfDay(day) < startOfDay(now);
}

/** Дальше, чем на год вперёд. Такую дату вводят опечаткой в годе. */
export function isTooFarAhead(day: Date, now: Date = new Date()): boolean {
  return startOfDay(day) - startOfDay(now) > MAX_AHEAD_DAYS * 86_400_000;
}

/**
 * Дни, которые в календаре недоступны: прошлое и дальше года вперёд.
 *
 * Те же границы держит сервер (400 invalid_input). Здесь они нужны
 * раньше — чтобы отказ не приходил на день, который пикер показал
 * выбираемым.
 */
export function isDisabledDay(day: Date, now: Date = new Date()): boolean {
  return isPastDay(day, now) || isTooFarAhead(day, now);
}

/**
 * Своя выкладка на этот день, если она есть.
 *
 * Отменённые не в счёт: их сняли с плана, и день снова свободен —
 * ровно так же считает сервер, отвечая 409 day_taken.
 *
 * Проверяем до запроса, чтобы сказать это сразу и в самом окне: отказ,
 * прилетевший после клика, человек относит к сбою, а не к своему
 * расписанию.
 */
export function takenOn(items: readonly Publication[], ymd: string): Publication | null {
  return items.find((p) => p.status !== 'cancelled' && p.due_date.slice(0, 10) === ymd) ?? null;
}

/** Выкладку завёл себе сам креатор, а не поручил менеджер. */
export function isSelfAdded(pub: Publication): boolean {
  // Проверяем НАЛИЧИЕ поля: у плановых выкладок ключа нет вовсе, и
  // сравнение с false здесь ничего не значит.
  return pub.self_added !== undefined && pub.self_added !== false;
}
