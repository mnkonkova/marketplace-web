/**
 * Какой месяц показать в календаре выкладок.
 *
 * Календарь рисует ОДИН месяц и открывался всегда на текущем. Выкладки
 * при этом стоят там, где идёт период проекта, а период катится от даты
 * первой публикации и текущему календарному месяцу не равен. У проекта с
 * одиннадцатью выкладками десять приходилось на август — заказчик
 * открывал сентябрь, видел одну точку в пустой сетке и говорил, что
 * календарь выкладок не показывает. Он и не показывал: они были в
 * соседнем месяце, и ничто на это не намекало.
 *
 * Разбор вынесен из компонента, потому что это единственное место, где
 * календарь что-то РЕШАЕТ, а не рисует. Внутри компонента оно
 * проверялось бы только через отрисованную сетку, то есть не
 * проверялось бы вовсе.
 */

/** Месяц в виде ГГГГ-ММ. Строки сравниваются как есть — порядок тот же. */
export type Month = string;

const MONTH_RE = /^\d{4}-(0[1-9]|1[0-2])$/;

/** Текущий месяц в формате ГГГГ-ММ — его же ждёт ручка календаря. */
export function currentMonth(now: Date = new Date()): Month {
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`;
}

/**
 * Месяц, который стоит открыть.
 *
 * Правило:
 *
 *  • в текущем месяце что-то есть — открываем его. Заказчик пришёл
 *    смотреть, что происходит сейчас, и уводить его в прошлое нельзя.
 *  • нет — открываем ПОСЛЕДНИЙ месяц с выкладками до текущего: это то,
 *    что вышло недавно, и именно про него спрашивают.
 *  • всего этого нет (проект только начинается, всё запланировано
 *    вперёд) — открываем БЛИЖАЙШИЙ будущий.
 *  • список пуст — оставляем как есть: выкладок нет вовсе, и прыгать
 *    некуда. Пустой календарь в этом случае — правильный ответ, а не
 *    потеря.
 *
 * Мусор в списке выбрасываем, а не подставляем: месяц не в формате
 * ГГГГ-ММ мы не умеем открыть, и попытка обернулась бы пустой сеткой без
 * подписи, то есть тем же симптомом, который тут и лечится.
 */
export function monthToOpen(months: readonly Month[], current: Month): Month {
  const clean = (months ?? []).filter((m) => MONTH_RE.test(m)).sort();
  if (!clean.length || clean.includes(current)) return current;
  const past = clean.filter((m) => m < current);
  if (past.length) return past[past.length - 1];
  return clean[0];
}

/**
 * Куда уйти из пустого месяца: ближайший с выкладками с каждой стороны.
 *
 * Нужно подписи под пустой сеткой. «Выкладок нет» само по себе неотличимо
 * от «данные не доехали»; «в сентябре нет, ближайшие в августе» — это
 * уже ответ, да ещё и с дорогой туда.
 *
 * Пусто с обеих сторон означает, что выкладок нет во всём проекте, — и
 * тогда никакой подписи про «соседние месяцы» быть не должно: она
 * обещала бы то, чего нет.
 */
export function neighbourMonths(
  months: readonly Month[],
  current: Month,
): { before: Month | null; after: Month | null } {
  const clean = (months ?? []).filter((m) => MONTH_RE.test(m) && m !== current).sort();
  const past = clean.filter((m) => m < current);
  const future = clean.filter((m) => m > current);
  return {
    before: past.length ? past[past.length - 1] : null,
    after: future.length ? future[0] : null,
  };
}

/** «август 2026» — подпись месяца в предложении, а не заголовком. */
const MONTHS_OF = [
  'январе',
  'феврале',
  'марте',
  'апреле',
  'мае',
  'июне',
  'июле',
  'августе',
  'сентябре',
  'октябре',
  'ноябре',
  'декабре',
];

/**
 * Месяц предложным падежом: «в августе», «в январе 2027».
 *
 * Год дописываем, только когда он не подразумевается: подпись стоит
 * внутри фразы, и «в августе 2026 года» там, где год и так текущий,
 * читается как канцелярит.
 */
export function monthInWords(month: Month, current: Month = currentMonth()): string {
  if (!MONTH_RE.test(month)) return '';
  const [y, m] = month.split('-').map(Number);
  const name = MONTHS_OF[m - 1] ?? '';
  const sameYear = month.slice(0, 4) === current.slice(0, 4);
  return sameYear ? name : `${name} ${y}`;
}

/**
 * Полоса месяцев под сеткой: где у проекта есть выкладки.
 *
 * Одной сетки мало даже тогда, когда она не пуста. У проекта с
 * одиннадцатью выкладками одна приходилась на сентябрь, а десять — на
 * август: календарь честно рисовал сентябрь с единственной точкой, и это
 * и читалось как «выкладок нет, что-то сломалось». Полоса отвечает на
 * вопрос раньше, чем он задан: вот месяцы, в которых что-то есть, вы
 * смотрите на этот.
 *
 * Показанный месяц входит в полосу всегда, даже когда выкладок в нём нет:
 * иначе получилась бы полоса, в которой не отмечен ни один пункт, — а
 * человек стоит на одном из них.
 */
export function monthStrip(months: readonly Month[], current: Month): Month[] {
  const clean = new Set((months ?? []).filter((m) => MONTH_RE.test(m)));
  if (MONTH_RE.test(current)) clean.add(current);
  return [...clean].sort();
}

/** «авг. 2026» — короткая подпись месяца для полосы. */
const MONTHS_SHORT = [
  'янв.',
  'фев.',
  'мар.',
  'апр.',
  'мая',
  'июн.',
  'июл.',
  'авг.',
  'сен.',
  'окт.',
  'ноя.',
  'дек.',
];

/**
 * Месяц коротко: «авг.», а с чужим годом — «авг. 2025».
 *
 * Год дописываем только когда он отличается от года показанного месяца:
 * в полосе из трёх соседних месяцев одного года год — шум, а на переходе
 * через Новый год без него «дек.» и «янв.» не отличить по порядку.
 */
export function monthShort(month: Month, current: Month = currentMonth()): string {
  if (!MONTH_RE.test(month)) return '';
  const [y, m] = month.split('-').map(Number);
  const name = MONTHS_SHORT[m - 1] ?? '';
  return month.slice(0, 4) === current.slice(0, 4) ? name : `${name} ${y}`;
}
