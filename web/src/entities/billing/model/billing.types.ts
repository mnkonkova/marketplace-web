/**
 * Откуда взялся «типичный ролик».
 *
 * Не украшение: человеку говорят «до ступени 20 роликов», и он вправе
 * знать, на чьих данных это посчитано. «По твоим роликам» и «ориентир по
 * площадке» — разные обещания, и второе не должно выдавать себя за
 * первое. Поэтому подпись стоит рядом с числом, а не прячется в
 * подсказку.
 *
 * Словарь общий с сервером: лесенку «свои → проект → значение по
 * умолчанию» считает он, здесь только называются её ступени.
 */
export type TypicalSource = 'creator' | 'project' | 'default';

// ---- периоды проекта ----
//
// Проект не живёт календарными месяцами. Первый период начинается датой
// первой публикации и длится ровно месяц, дальше они катятся от той же
// даты: вышел первый ролик 15-го — периоды с 15-го по 14-е. Поэтому в
// подписях период называется периодом и показывается датами: «сентябрь»
// про него — неправда, а разница между «сентябрём» и «15.09 — 14.10» и
// есть то главное, что человек должен понять с первого взгляда.

// open — период идёт, числа ещё изменятся; locked — подытожен через две
// недели после конца, срез снят, суммы заморожены. Ручного подытога нет.
export type PeriodStatus = 'open' | 'locked';

// Что видно про период всем: номер, границы и состояние. Ниже три типа
// поверх этой основы — по одному на роль, и это не педантизм: в периоде
// лежит перенос остатка ПО ОБЕИМ сторонам, а клиентская сторона такая же
// коммерческая тайна для креатора, как креаторская для заказчика. Один
// общий тип означал бы, что каждое новое поле уезжает наружу само.
export interface PeriodBase {
  // Какой это период по счёту: первый, второй, третий. Он же — значение
  // ?period=N в запросе.
  seq: number;
  // Границы включительно с обеих сторон. Их считает сервер: правило
  // периода живёт в одном месте, иначе браузер продолжит рисовать старые
  // даты после первой же его правки.
  starts_on: string;
  ends_on: string;
  status: PeriodStatus;
  // На какую дату сняты числа подытоженного периода: конец плюс две
  // недели. Это отсечка, а не момент фиксации, — воркер мог опоздать.
  // Рядом с числами подытоженного периода показываем именно её: просто
  // «за период» не отвечает на вопрос, когда их мерили.
  snapshot_as_of?: string;
  // Числам не на что опереться: поденная статистика за период уже
  // удалена, и они подтянуты, а не измерены.
  //
  // Не то же самое, что «предварительно» (Accrual.is_preview): то про
  // период, который ещё идёт, это — про подытоженный, но опирающийся на
  // пустоту. Могут стоять одновременно, и схлопывать их в одну плашку
  // нельзя: первое значит «подожди», второе — «перепроверь».
  snapshot_approx?: boolean;
}

// Период глазами менеджера и админа: обе стороны переноса и вся механика
// цепочки. Приходит из /manager/… и /admin/….
export interface ProjectPeriod extends PeriodBase {
  id: string;
  project_id: string;
  prev_period_id?: string;
  locked_at?: string;
  // Перенос остатка ступени тарифа, в просмотрах. Ступень — 100 000;
  // недобравший до полной остаток едет в следующий период. Стороны
  // разные: считаются по своим ставкам и разъедутся.
  carry_in_client: number;
  carry_out_client: number;
  carry_in_creator: number;
  carry_out_creator: number;
}

// Период глазами заказчика: его сторона переноса и ничего больше.
// Идентификаторов периода здесь нет намеренно — цепочка переноса наша
// внутренняя механика.
export interface ClientPeriod extends PeriodBase {
  carry_in_client: number;
  carry_out_client: number;
}

// Период глазами креатора: его сторона переноса. Сколько просмотров
// пришло из прошлого периода и сколько уйдёт в следующий.
export interface CreatorPeriod extends PeriodBase {
  carry_in_creator: number;
  carry_out_creator: number;
}

// Период в ответе про деньги проекта: менеджерский или клиентский —
// смотря кто спрашивал. Общего у них ровно то, что рисует экран.
export type BillingPeriod = ProjectPeriod | ClientPeriod;

// draft → approved → paid. Утверждённая строка пересчётом не трогается —
// это и есть «период закрыт»; выплатить неутверждённую нельзя.
export type AccrualStatus = 'draft' | 'approved' | 'paid';

export interface Accrual {
  id: string;
  // Строка посчитана сервером на лету, в базе её нет: так выглядит месяц,
  // который ещё не пересчитывали. Цифры настоящие, но утвердить и
  // выплатить такую строку нельзя — сперва её сохраняет «Пересчитать».
  is_preview?: boolean;
  project_id: string;
  creator_user_id: string;
  creator_name?: string;
  // Начало периода, которому принадлежит начисление. Периоды катятся от
  // даты первой публикации проекта, а не по календарю, — первым числом
  // месяца это не бывает.
  period_start: string;
  status: AccrualStatus;
  // Каким по приоритету человек попал в подборку заказа: «приоритет 1»
  // в «Команде месяца» у заказчика. 0 — проект заведён руками, и строку
  // «собрана по вашему приоритету» показывать не надо.
  priority?: number;
  salary: number;
  // Просмотры по ступеням тарифа: base — то, что попало под полную ставку
  // (до порога на каждом ролике), over — то, что сверх. Обе части, потому
  // что по одному итогу не разобрать, почему бонус именно такой.
  views_base: number;
  views_over: number;
  views_total: number;
  views_bonus: number;
  clicks: number;
  click_bonus: number;
  // Недосданное не оплачивается, вычет пропорционален недостаче.
  videos_planned: number;
  videos_delivered: number;
  deduction: number;
  total: number;
  // Что получает сам креатор: те же правила, но по его ставкам. Приходит
  // только менеджеру — заказчику эта сторона сделки не отдаётся вовсе.
  // Совпадает с total, пока креаторская сторона тарифа не заполнена.
  payout_salary?: number;
  payout_deduction?: number;
  payout_views_bonus?: number;
  payout_click_bonus?: number;
  payout_total?: number;
  calculated_at?: string;
  approved_at?: string;
  paid_at?: string;
}

// Итог периода. Считается на сервере из тех же строк: складывать их ещё
// раз на фронте значит получить на двух экранах два разных числа.
export interface PeriodTotals {
  salaries: number;
  views_bonus: number;
  click_bonus: number;
  deductions: number;
  total: number;
  views: number;
  // Сколько выкладок стояло и сколько закрыто: «по 6 роликам» в шапке
  // считается отсюда, а не сложением строк.
  videos: number;
  videos_delivered: number;
  // Во сколько обошлась тысяча просмотров. Пусто, пока просмотров нет —
  // делить не на что.
  cost_per_1000?: number;
  // Сколько должны креаторам и что остаётся площадке. Только у менеджера:
  // заказчику наша маржа не отдаётся, и в его ответе этих полей нет.
  payouts?: number;
  margin?: number;
}

// UTM-метка креатора. Ставит менеджер, креатор только видит.
export interface UtmLink {
  creator_user_id: string;
  creator_name?: string;
  url: string;
  // Заполняется снаружи, из аналитики. Пока бонус за переходы выключен,
  // число справочное.
  clicks: number;
  updated_at?: string;
}

export interface ProjectBilling {
  terms?: BillingTerms;
  payments?: Payment[];
  // За запрошенный месяц. Заказчик их тоже видит: в макете это «Команда
  // месяца» — кто сколько роликов сдал и во сколько это обошлось. Он за
  // них и платит, поэтому «60 000 + 5 850» — его счёт, а не чужая
  // зарплата. UTM-меток у него по-прежнему нет: это инструмент менеджера.
  accruals?: Accrual[];
  utm?: UtmLink[];
  totals?: PeriodTotals;
  // Какой период показан и в каком он состоянии. Отсюда же понятно,
  // почему строки помечены «предварительно», и на какую дату сняты
  // числа, если период уже подытожен.
  period?: BillingPeriod;
}

/**
 * Что даст следующая ступень. ПРОГНОЗ, а не начисленное.
 *
 * Правый конец денежной полосы в кабинете креатора. Считает его сервер —
 * тем же кодом, что и настоящую выплату: разницей между выплатой сейчас
 * и выплатой при выросших просмотрах. Отдельной формулы «для прогноза»
 * нет намеренно, иначе она разошлась бы с фактической выплатой, и
 * разошлась бы молча.
 *
 * Почему это всё-таки прогноз: куда лягут будущие просмотры — в полную
 * ставку или в пониженную после порога — зависит от того, на каком
 * ролике они наберутся. Отсюда «примерно» в подписи; подписать это
 * заработанным нельзя, человек будет ждать денег, которых ещё нет.
 */
export interface NextStepForecast {
  /** Размер ступени в просмотрах. */
  step_views: number;
  /**
   * Сколько просмотров осталось до ступени — вместе с перенесённым
   * остатком: он уже в счёте, и не учесть его значило бы отправить
   * человека добирать то, что у него уже есть.
   */
  views_to_go: number;
  /** Сколько переноса учтено. Ноль, пока ступенчатый тариф не выпущен. */
  carry_in_included: number;
  /** Сколько эти просмотры принесут ему самому, копейки. */
  forecast_payout: number;
}

// Взгляд креатора: условия, свои начисления по всем месяцам проекта
// (свежие первыми) и своя метка. Чужих цифр здесь нет.
export interface CreatorEarnings {
  terms?: BillingTerms;
  accruals?: Accrual[];
  utm?: UtmLink;
  // Текущий период его глазами — по нему строится шкала.
  period?: CreatorPeriod;
  // Все периоды проекта. Начисления приходят разом по всем периодам, и
  // границы нужны каждой строке истории, а не только текущей: строка
  // знает только period_start, а «с какого по какое» — здесь.
  //
  // Границы приходят с сервера и нигде не выводятся из period_start
  // прибавлением месяца: правило периода живёт в одном месте, иначе
  // после первой же его правки браузер молча продолжит рисовать старые
  // даты, и связать одно с другим будет некому.
  periods?: CreatorPeriod[];
  // Ориентир: типичный ролик и обезличенное сравнение с проектом.
  benchmark?: ProjectBenchmark;
  /**
   * Что даст следующая ступень. Может не прийти, и это штатно: у проекта
   * нет периодов или пустой тариф — считать не по чему. Ноль в этом
   * случае читался бы как «ступень ничего не даст», а это другое
   * утверждение.
   */
  next_step_forecast?: NextStepForecast;
}

// Ориентир проекта. Имён и чьих-либо отдельных чисел здесь нет и быть не
// может: любая строка, по которой угадывается человек, превращает
// агрегат в чужие данные.
export interface ProjectBenchmark {
  // Типичный ролик — готовое число с сервера. Лесенку «история самого
  // креатора → медиана проекта → значение по умолчанию» считает он: это
  // правило, а второй копии правила в браузере быть не должно.
  typical_video_views: number;
  // На чьих данных оно посчитано. Подпись обязательна рядом с числом:
  // «до ступени 20 роликов» по своей истории и по среднему по площадке —
  // разные обещания.
  typical_video_source: TypicalSource;
  // Медиана просмотров зрелых роликов проекта. Может не прийти, и это
  // штатно: ниже порога обезличивания (десять зрелых роликов минимум от
  // трёх человек) медиана перестаёт быть агрегатом и превращается в
  // результат соседа.
  project_median_views?: number;
  // Где человек относительно неё: доля зрелых роликов проекта, у которых
  // просмотров меньше, чем у его медианного ролика. По тому же порогу —
  // нет числа, нет и блока, без объяснений и пустого места.
  my_percentile?: number;
  // Сколько зрелых роликов вошло в расчёт: объясняет, насколько
  // ориентиру можно верить.
  mature_videos?: number;
  // Сколько зрелых роликов у него самого. Его собственное число,
  // обезличивать нечего; заодно объясняет, почему источник именно такой.
  my_mature_videos?: number;
}

// ---- сводка заказчика по всем проектам ----
//
// Такого среза в продукте не было вовсе: всё считалось внутри одного
// проекта, и заказчик с тремя проектами складывал числа в уме или в
// табличке. Отсюда и главный вопрос этого экрана — «сколько мне стоит
// тысяча просмотров», — на который в проекте по отдельности ответа нет.
//
// Слово «охват» здесь не встречается ни разу, и это не вкусовщина: мы
// считаем ПРОСМОТРЫ, а на различии «показ против просмотра» построена
// вся коммерческая аргументация. Назвать одно другим — обещать то, чего
// мы не собираем.

/** Проект в сводке: идёт или ещё не начался. */
export type OverviewState = 'running' | 'not_started';

/**
 * Окно, за которое считается сводка.
 *
 * Три и только три: неделя, месяц, квартал. Произвольные даты здесь не
 * нужны — сводку показывают начальству, а «17 авг. — 15 сент.» человек
 * выбирает не сам, он выбирает «месяц».
 */
export type OverviewRange = 'week' | 'month' | 'quarter';

export interface OverviewViews {
  /** ЗА ВСЁ ВРЕМЯ, а не за окно. Окно живёт в `window`. */
  total: number;
  /**
   * Все пять площадок всегда, включая нулевые: пропавший столбик
   * читается как сбой, а не как ноль.
   *
   * Осталось от сводки до дашборда: разбор по площадкам теперь приходит
   * в `platforms` целиком (с ER, приростом и рядом). Поле опционально,
   * чтобы сводка не рассыпалась ни на старом ответе, ни на новом.
   */
  by_platform?: Record<string, number>;
}

/**
 * Всё, что посчитано ЗА ОКНО.
 *
 * Отдельным блоком, а не полями рядом с итогами за всё время, и это не
 * формальность: «3 млн просмотров, +34% к прошлому месяцу» при числе за
 * всё время читается как «за месяц 3 млн» и врёт даже тогда, когда оба
 * числа верны. Разные имена не дают перепутать их ни в коде, ни на
 * экране: рядом с оконным числом всегда стоит период, рядом с общим —
 * «по всем проектам».
 *
 * Приростов МОЖЕТ НЕ БЫТЬ — когда сравнивать не с чем: прошлого такого
 * же окна не существует или в нём не собирали. Это не ноль: ноль
 * означает «сравнили и не изменилось». Подменять отсутствие нулём —
 * рисовать зелёную стрелку там, где мы просто не знаем.
 */
export interface OverviewWindow {
  views: number;
  views_delta_pct?: number;
  engagement: number;
  engagement_delta_pct?: number;
  /**
   * Комментарии отдельным числом: это единственный вид отклика, который
   * человек написал руками, и плитка у него своя.
   */
  comments: number;
  comments_delta_pct?: number;
  /** Пусто — делить не на что: просмотров за окно нет, и ER не существует. */
  er_percent?: number;
  /**
   * Пункты, а не проценты: ER сам измеряется в процентах, и «вырос на
   * 7%» от 4,4% читается двояко — до 4,7 или до 11,4.
   */
  er_delta_pp?: number;
  /**
   * Хоть одна площадка репостов не отдала — число занижено. Про это
   * говорит звёздочка у самой цифры, а не сноска внизу экрана.
   */
  er_without_shares?: boolean;
}

/**
 * Площадка в дашборде: сколько дала за всё время и сколько за окно.
 *
 * Два набора чисел намеренно. Дашборд показывает оконные — иначе доли
 * не сойдутся с главным числом героя, которое тоже оконное. Числа за всё
 * время остаются для блоков про деньги, где окно ни при чём.
 *
 * Долю сервер присылает свою, но ширину куска полосы мы считаем из
 * просмотров: округлённые до целых доли пяти площадок дают в сумме то
 * 99, то 101 процент, и полоса либо не сходится справа, либо
 * переполняется.
 */
export interface OverviewPlatform {
  platform: string;
  /** За всё время. */
  views: number;
  share_pct: number;
  /** За окно. Именно эти числа стоят в дашборде. */
  window_views?: number;
  window_share_pct?: number;
  /** ER за окно. Пусто — делить не на что. */
  er_percent?: number;
  er_without_shares?: boolean;
  /** Прирост окна к прошлому такому же. Может не быть. */
  delta_pct?: number;
  /** Поденный прирост за окно. Дни без сбора в ряду отсутствуют. */
  series: OverviewPoint[];
}

/**
 * Ролик, который разошёлся. Со ссылкой: главное здесь — что его можно
 * открыть и проверить, а не что мы написали красивое число.
 */
export interface OverviewTopVideo {
  publication_id: string;
  title: string;
  platform: string;
  published_at: string;
  views: number;
  url: string;
}

/**
 * С чем сравниваем цену тысячи. Источник и дата замера — не мелкий
 * шрифт для юристов: цифра рынка без них через год начнёт врать, а с
 * ними её можно проверить, и продаёт здесь именно проверяемость.
 */
export interface MarketBenchmark {
  key: string;
  title: string;
  /** Цена тысячи у рынка, копейки — как и все деньги в этом домене. */
  price_per_1000: number;
  source: string;
  /** Когда замеряли, ГГГГ-ММ-ДД. */
  measured_on: string;
  /** Во сколько раз наша тысяча дешевле. Считает сервер. */
  times_cheaper: number;
}

/** Деньги заказчика по всем проектам, в копейках. */
export interface OverviewMoney {
  /** По подытоженным периодам: окончательное, из срезов. */
  locked: number;
  /** По текущим: предварительное, числа ещё вырастут. */
  current: number;
  /** locked + current — «сколько всего стоит работа на сегодня». */
  total: number;
  /**
   * Сколько уже переведено: подтверждённые платежи. Отдельно от total
   * намеренно — это разные вопросы: «сколько стоит» и «сколько внесено».
   */
  paid: number;
}

export interface OverviewProject {
  project_id: string;
  title: string;
  state: OverviewState;
  /** Текущий период. Нет у не начавшегося проекта. */
  period?: ClientPeriod;
  views: number;
  /** Счёт по проекту: подытоженные периоды плюс текущий. */
  total: number;
  /** Пусто, пока просмотров нет: делить не на что. */
  cost_per_1000?: number;
}

/**
 * Точка графика: ПРИРОСТ за день, а не «всего на эту дату».
 *
 * Разница тут на порядок: накопительный ряд рисует одну восходящую
 * кривую, из которой не видно ни одного удачного дня, а прирост
 * показывает ровно то, ради чего график и смотрят. Не сглаживаем и не
 * прячем колебания: провал в ряду — это факт, а не шум.
 */
export interface OverviewPoint {
  date: string;
  views_gained: number;
}

export interface ClientOverview {
  projects_total: number;
  projects: OverviewProject[];
  views: OverviewViews;
  money: OverviewMoney;
  /**
   * Стоимость тысячи просмотров по всем проектам, копейки. Главное число
   * экрана: оно падает по мере роста, и это лучший аргумент, какой можно
   * показать. Считается из ФАКТИЧЕСКИХ сумм и просмотров, а не из ставки
   * тарифа: у разных проектов разные версии условий, и средняя ставка
   * соврала бы. Пусто, пока просмотров нет.
   */
  cost_per_1000?: number;
  /**
   * Хотя бы у одного подытоженного периода числа подтянуты: поденную
   * статистику к моменту подытога уже удалили. Сводка, часть чисел
   * которой приблизительна, обязана сказать об этом, а не выглядеть
   * точной.
   */
  snapshot_approx?: boolean;
  /** Ряд для графика, последние 90 дней. */
  series: OverviewPoint[];
  generated_at: string;

  // ---- дашборд: всё, что считается ЗА ОКНО ----
  //
  // Блоки опциональны намеренно. Сводка старше дашборда и живёт на том
  // же ответе; пока бэкенд раскатывается, часть полей приходит, часть
  // нет, и экран обязан показывать то, что доехало, а не падать целиком.

  /** Какое окно посчитал сервер. Может отличаться от запрошенного. */
  range?: OverviewRange;
  /** Готовая подпись окна: «17 авг. — 15 сент. 2026». Границы считает сервер. */
  range_label?: string;
  /** Числа за окно. Рядом с каждым из них на экране стоит период. */
  window?: OverviewWindow;
  /** Разбор по площадкам. Все пять, включая пустые. */
  platforms?: OverviewPlatform[];
  /** Залетевшие ролики за окно, уже отсортированные. */
  top_videos?: OverviewTopVideo[];
  /**
   * С чем сравнить цену тысячи. Считается от цены ЗА ВСЁ ВРЕМЯ, поэтому
   * и на экране стоит рядом с деньгами, а не под оконным героем. Пусто,
   * пока просмотров нет: сравнивать нечего, и блок тогда не рисуется.
   */
  market?: MarketBenchmark[];
  /** Когда последний раз собирали данные площадок. */
  collected_at?: string;
}
