// Типы домена «деньги проекта» — DTO из marketplace-api/internal/billing.
//
// ВСЕ СУММЫ В КОПЕЙКАХ. Делить на 100 только при показе, считать — никогда:
// деление на тысячу просмотров в целых рублях расходится в последнем знаке,
// и «746 ₽ за 1000» у менеджера и заказчика получались разными.

// Условия проекта — снимок, а не ссылка на действующий прайс: правка
// прайса не переписывает историю уже идущего проекта.
export interface BillingTerms {
  /**
   * Фикс ЗА РОЛИК: клиент платит столько за каждую вышедшую выкладку,
   * креатор столько получает. Этим фикс отличается от ступеней:
   * ступени про рост просмотров, фикс — про объём работы.
   *
   * Занимает место нижней ступени лесенки — там и был фикс за период.
   * Пусто — фикса за ролик нет, цена берётся из лесенки, как раньше.
   */
  fee_per_video?: number | null;
  creator_fee_per_video?: number | null;

  project_id: string;
  // Оклад креатора за месяц.
  salary_per_month: number;
  // За какой объём назван оклад: «30 видео первый месяц, 60 со второго».
  // Без этой подписи сумма оклада ни о чём не говорит.
  videos_first_month?: number;
  videos_next_months?: number;
  // Ставка за тысячу просмотров до порога и свыше. Вторая ниже намеренно:
  // так виральный ролик не съедает бюджет заказчика.
  rate_per_1000_views: number;
  rate_per_1000_views_over: number;
  // Порог НА РОЛИК, суммой по пяти площадкам. 0 — порога нет, весь объём
  // идёт по полной ставке.
  bonus_views_threshold: number;
  // Переходы устроены так же, но порог здесь МЕСЯЧНЫЙ. click_bonus_rate
  // пустой — источник кликов не подключён, бонус не считается, поля в
  // тарифе есть.
  click_bonus_rate?: number;
  click_bonus_rate_over?: number;
  click_bonus_threshold?: number;
  // Креаторская сторона тарифа: что получает исполнитель. Пусто — «столько
  // же, сколько платит клиент»: до заполнения этих полей выплата равна
  // счёту и маржи у платформы нет. Две стороны нужны потому, что это
  // разные деньги: счёт заказчику и обязательство перед креатором.
  creator_salary_per_month?: number;
  creator_rate_per_1000_views?: number;
  creator_rate_per_1000_views_over?: number;
  // Ступени тарифа: произвольное число порогов объёма и цена периода на
  // каждом. Непустая лесенка отменяет прежнюю пару «ставка за тысячу до
  // и после порога» — это другое правило счёта.
  steps?: TariffStep[];
  // Гарантия в ПРОСМОТРАХ, а не в деньгах — так в оферте. Недобрали за
  // период — он всё равно оплачивается, а недостающие просмотры уходят
  // в долг и гасятся из следующего.
  guarantee_views?: number;
  // KPI по подписчикам. Сборщика подписчиков в продукте нет: ставка
  // объявляется, а само число вписывает менеджер — как переходы по UTM.
  // Пусто — KPI не считается вовсе.
  subscriber_rate?: number;
  creator_subscriber_rate?: number;
  // С какой версии прайса сняты числа. Только для истории.
  terms_version_id?: string;
  updated_at?: string;
}

/**
 * Ступень тарифа.
 *
 * Порог ОБЪЁМА и цена ПЕРИОДА на нём, а не цена за каждые сто тысяч
 * просмотров: так звучит коммерческое предложение («оклад плюс KPI на
 * 300 000 просмотров»), и так его читает заказчик. Набрали за период
 * столько-то — период стоит столько-то.
 *
 * Деньги здесь, как и везде, в КОПЕЙКАХ, и считает их только сервер.
 */
export interface TariffStep {
  /** С какого объёма просмотров за период действует ступень. */
  from_views: number;
  /** Сколько стоит период заказчику на этой ступени. */
  client_fee: number;
  /** Оклад креатору на ступени. Пусто — столько же, сколько у заказчика. */
  creator_fee?: number | null;
}

/**
 * Строка реестра тарифов: ПРОЕКТ со своими условиями.
 *
 * Прайс площадки один на всех, а договариваются с каждым заказчиком
 * отдельно. Вопрос к разделу «Прайс» звучит не «какой у нас прайс», а
 * «по каким условиям идёт вот этот проект и чем он отличается от
 * соседнего» — на него и отвечает таблица.
 */
export interface TariffRow {
  project_id: string;
  title: string;
  client_name?: string;
  manager_name?: string;
  status: string;
  /**
   * Снимок условий заведён. false — проект считается ПО НУЛЯМ, и экран
   * денег показывает ровные нули: выглядит как «ещё не начислили».
   */
  has_terms: boolean;
  /** Считается лесенкой. false при has_terms — старая модель. */
  stepped: boolean;
  steps_count: number;
  /** Вилка цены периода заказчику, копейки: нижняя и верхняя ступень. */
  min_fee: number;
  max_fee: number;
  /** Числа старой модели — показываем там, где ступеней нет. */
  salary_per_month: number;
  rate_per_1000_views: number;
  guarantee_views?: number;
  updated_at?: string;
}

export interface BillingTermsInput {
  /**
   * Фикс за ролик, в копейках: клиенту и креатору. null — фикса за
   * ролик нет, цена берётся из лесенки, как раньше.
   */
  fee_per_video?: number | null;
  creator_fee_per_video?: number | null;

  salary_per_month: number;
  rate_per_1000_views: number;
  rate_per_1000_views_over: number;
  bonus_views_threshold: number;
  videos_first_month?: number;
  videos_next_months?: number;
  // null — выключить бонус за переходы: источник кликов не подключён.
  // Отличается от 0, который значит «ставка задана и равна нулю».
  click_bonus_rate?: number | null;
  click_bonus_rate_over?: number | null;
  click_bonus_threshold?: number | null;
  // null — «как у клиента»: платформа ничего не удерживает.
  creator_salary_per_month?: number | null;
  creator_rate_per_1000_views?: number | null;
  creator_rate_per_1000_views_over?: number | null;
  // Лесенка целиком: сервер переписывает её заменой, а не правкой по
  // одной строке — ступень удаляют не реже, чем добавляют.
  steps?: TariffStep[];
  // Гарантия в ПРОСМОТРАХ, а не в деньгах — так в оферте. Недобрали за
  // период — он всё равно оплачивается как гарантия, а недостающие
  // просмотры уходят в долг и гасятся из следующего.
  guarantee_views?: number | null;
  // null — KPI по подписчикам не считаем вовсе. Отличается от 0, который
  // значит «ставка задана и равна нулю».
  subscriber_rate?: number | null;
  creator_subscriber_rate?: number | null;
}

