import { defineConfig, devices } from '@playwright/test';
import { join } from 'node:path';

// __dirname, а не import.meta: пакет фронта — CommonJS, и ES-модульная
// форма здесь просто не выполнится.
const here = __dirname;

/**
 * Браузерные сквозные тесты.
 *
 * Гоняются по уже поднятому стеку: `make run` в бэкенде и `ng serve` во
 * фронте. Поднимать их самим отсюда — соблазнительно, но тогда падение
 * стека выглядит как падение теста, а разбираться приходится в обоих.
 *
 * Браузер берём тот, что уже скачан для karma (PLAYWRIGHT_BROWSERS_PATH
 * в npm-скрипте), — второй раз качать хромиум незачем.
 */
/**
 * Медленные специи — обходы кнопок.
 *
 * `buttons-sweep` и `buttons-destructive` вдвоём занимают минут
 * двенадцать из четырнадцати: первый обходит каждую кнопку каждой роли,
 * второй жмёт всё, что меняет мир, и ждёт ответов сервера. Остальные
 * сто пятнадцать проходят примерно за минуту.
 *
 * Поэтому набора два. Быстрый (E2E_FAST=1, `npm run e2e:fast`) — перед
 * каждым пушем: он ловит ровно то, из-за чего этот раскол и появился, —
 * разметку кабинета, разошедшуюся со специями. Полный — перед выкаткой
 * и всегда, когда правились кнопки.
 *
 * Делим файлами, а не пометками в названиях: название специи здесь —
 * документация, и дописывать в него «@slow» значит портить её ради
 * запускалки.
 */
const SLOW_SPECS = ['**/buttons-sweep.spec.ts', '**/buttons-destructive.spec.ts'];

/**
 * Порядок наборов: сперва быстрые, обходы кнопок последними.
 *
 * Дело не в красоте отчёта. Обход жмёт каждую кнопку каждой роли с
 * перезагрузкой экрана перед каждой — шестнадцать минут непрерывных
 * загрузок, — и специи, шедшие после него по алфавиту, начинали
 * отваливаться по времени на ровном месте: `page.goto` не укладывался в
 * тридцать секунд, браузер ронял сессию. На спокойном стенде те же
 * сорок специй проходят за четыре минуты.
 *
 * Зависимость `dependencies` и делает очередь: быстрый набор целиком,
 * потом медленный. Заодно это честнее по смыслу — обходу не нужен
 * свежий стенд, а остальным нужен.
 */
export default defineConfig({
  testDir: join(here, 'specs'),
  // Артефакты падений — ВНЕ проекта, за которым следит `ng serve`.
  //
  // Лежали они в `web/test-results`, то есть внутри watch'а дев-сервера:
  // первая же красная специя писала туда скриншот и трассу, дев-сервер
  // видел изменение файлов и начинал пересборку, а `page.goto`
  // следующей специи вставал на те самые тридцать секунд и падал по
  // времени. Та писала свои артефакты — и роняла следующую. Одна
  // настоящая поломка превращалась в десяток чужих, каждый со своей
  // непохожей ошибкой, и искали их порознь.
  outputDir: join(here, '..', '..', '.e2e-artifacts'),
  globalSetup: join(here, 'fixtures', 'world.ts'),
  globalTeardown: join(here, 'fixtures', 'teardown.ts'),
  timeout: 30_000,
  expect: { timeout: 7_000 },
  // Параллель выключена, хотя у каждой специи теперь свой проект.
  // Причина осталась одна, и она не про проекты: специи ходят по общему
  // стенду — общий каталог, общий список админки, общий рейт-лимитер, —
  // и гонка за них даёт мигающие падения, а не находки.
  workers: 1,
  fullyParallel: false,
  retries: 0,
  reporter: [['list']],
  use: {
    // Внешние шрифты в тестах не грузим — и это не экономия трафика.
    //
    // styles.scss тянет два @import с fonts.googleapis.com, а
    // `page.goto` ждёт события `load`, то есть и эти два запроса тоже.
    // Пока сеть отвечает — незаметно; стоит ей замяться, и переход
    // упирается в тридцатисекундный предел, падая с «Test timeout» на
    // ровном месте. В отчёте это выглядит как сломанный экран: в одном
    // прогоне шесть красных специй, в следующем шесть других, и все
    // проходят поодиночке. В трассе видно настоящую причину — запрос к
    // fonts.googleapis.com со статусом -1.
    //
    // Отсекаем на уровне резолвера: хост не находится мгновенно, шрифты
    // падают на запасные семейства из тех же правил, а проверяем мы не
    // начертание.
    launchOptions: {
      args: [
        '--host-resolver-rules=MAP fonts.googleapis.com ~NOTFOUND,' +
          ' MAP fonts.gstatic.com ~NOTFOUND',
      ],
    },
    baseURL: process.env.E2E_BASE_URL ?? 'http://localhost:4200',
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'ru-RU',
  },
  projects: [
    {
      name: 'chromium',
      testIgnore: SLOW_SPECS,
      use: { ...devices['Desktop Chrome'] },
    },
    // Обходы кнопок. В быстром наборе (E2E_FAST=1) проекта нет вовсе —
    // не «пропущен», а не заведён: пропущенные специи в отчёте выглядят
    // как забытые.
    ...(process.env.E2E_FAST
      ? []
      : [
          {
            name: 'buttons',
            testMatch: SLOW_SPECS,
            dependencies: ['chromium'],
            use: { ...devices['Desktop Chrome'] },
          },
        ]),
  ],
});
