import { dropStaleSandboxes } from './world';

/**
 * Убрать за прогоном всё, что заводили песочницы.
 *
 * Обычно за собой убирает сам тест — `afterAll` отрабатывает и после
 * падения. Но прогон могли прервать с клавиатуры или уронить на посеве,
 * и тогда брошенный проект живёт в списках вечно и меняет ожидания
 * соседним специям. Эта уборка — второй рубеж, а не первый: если она
 * начнёт что-то находить регулярно, значит сломалась уборка в спеке.
 */
export default function globalTeardown(): void {
  dropStaleSandboxes();
}
