import { expect, type Page } from '@playwright/test';

/**
 * Переходы по разделам — там, где экран на них поделён.
 *
 * Кабинеты переписаны по макетам «PrMarket», и устройство разделов стало
 * другим: на ДЕСКТОПЕ карточка проекта снова одна длинная страница, а
 * разделы прячет только тач-слой (data-sec, см. _prmarket-touch.scss).
 * Вкладки в прежнем смысле остались одни — в карточке проекта у
 * заказчика.
 *
 * Поэтому три помощника из четырёх больше ничего не нажимают. Это не
 * заглушка: спека по-прежнему говорит «открой начисления», и ответ «они
 * и так открыты» — правда про сегодняшний экран. Когда разделы вернутся
 * (или спеки поедут на телефон), правка будет здесь, а не в шестнадцати
 * файлах.
 */

/**
 * Что человек пришёл посмотреть на карточке проекта у заказчика.
 *
 * Это НЕ список вкладок — это список вопросов, и он нарочно длиннее
 * вкладок: «Команда» и «Статистика» своих вкладок не имеют, они лежат
 * внутри «Денег» и «Сводки». Спека при этом говорит «открой команду», а
 * не «открой четвёртую вкладку»: она проверяет команду, и читаться
 * должна так же.
 */
export type ClientTab =
  | 'Сводка'
  | 'Ролики'
  | 'Календарь'
  | 'Статистика'
  | 'Команда'
  | 'Деньги'
  | 'Доступы'
  | 'Переписка';

/**
 * В какой вкладке сейчас лежит искомое. Ключ, а не подпись: у вкладки
 * переписки подпись — ИМЯ менеджера, и искать её по тексту значило бы
 * завязать спеку на посев.
 */
const CLIENT_TAB_OF: Record<ClientTab, string> = {
  Сводка: 'summary',
  Ролики: 'videos',
  Календарь: 'calendar',
  Статистика: 'summary',
  Команда: 'money',
  Деньги: 'money',
  // «Доступы и бот»: аккаунты, с которых выходят ролики, и
  // уведомления в телеграм.
  Доступы: 'access',
  Переписка: 'chat',
};

/**
 * Открыть раздел карточки проекта заказчика, где лежит нужное.
 *
 * Ждём саму полосу вкладок, а не просто кликаем: карточка тянет отчёт, и
 * до его приезда вкладок на экране нет вовсе — клик «вслепую»
 * промахивался бы мимо ещё не нарисованной кнопки.
 */
export async function openClientTab(page: Page, name: ClientTab): Promise<void> {
  const key = CLIENT_TAB_OF[name];
  const tabs = page.locator('.ptabs');
  await expect(tabs, 'полоса вкладок проекта нарисована').toBeVisible({ timeout: 15_000 });
  const tab = tabs.locator(`button[data-tab="${key}"]`);
  await tab.click();
  await expect(tab, `раздел «${name}» открыт`).toHaveAttribute('aria-current', 'page');
}

