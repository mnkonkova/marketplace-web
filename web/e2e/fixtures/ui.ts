import { expect, type Page } from '@playwright/test';

/**
 * Переходы по вкладкам — там, где экран стал вкладочным.
 *
 * Карточка проекта у заказчика раньше была одной длинной страницей:
 * лента роликов, календарь, статистика, команда, счёт и переписка шли
 * подряд. Теперь это вкладки, и спека, которая ищет календарь сразу
 * после загрузки, не находит его не потому, что он сломан, а потому что
 * он не открыт. Держим переход в одном месте: следующая перестановка
 * вкладок правится здесь, а не в шести файлах.
 */

/**
 * Что человек пришёл посмотреть на карточке проекта.
 *
 * Это НЕ список вкладок — это список вопросов, и он нарочно длиннее
 * вкладок. Разделов было шесть, стало три: календарь и команда уехали к
 * выкладкам (планировать съёмку и смотреть, кто снимает, — одно дело),
 * статистика — к деньгам (просмотры и есть то, за что платят). Спека
 * при этом по-прежнему говорит «открой календарь», а не «открой вторую
 * вкладку»: она проверяет календарь, и читаться должна так же.
 *
 * Знание о том, где что теперь лежит, живёт одной таблицей ниже.
 * Следующая перестановка правится здесь, а не в шести файлах.
 */
export type ClientTab = 'Ролики' | 'Календарь' | 'Статистика' | 'Команда' | 'Деньги' | 'Переписка';

/** Раздел, в котором сейчас лежит искомое. */
const CLIENT_TAB_OF: Record<ClientTab, string> = {
  Ролики: 'Выкладки',
  Календарь: 'Выкладки',
  Команда: 'Выкладки',
  Статистика: 'Деньги',
  Деньги: 'Деньги',
  Переписка: 'Переписка',
};

/**
 * Открыть раздел карточки проекта заказчика, где лежит нужное.
 *
 * Ждём саму полосу вкладок, а не просто кликаем: карточка тянет отчёт,
 * и до его приезда вкладок на экране нет вовсе — клик «вслепую»
 * промахивался бы мимо ещё не нарисованной кнопки.
 */
export async function openClientTab(page: Page, name: ClientTab): Promise<void> {
  const section = CLIENT_TAB_OF[name];
  const tabs = page.locator('.tabs[role="tablist"]').last();
  await expect(tabs, 'полоса вкладок проекта нарисована').toBeVisible({ timeout: 15_000 });
  const tab = tabs.getByRole('tab', { name: new RegExp(`^${section}`) }).first();
  await tab.click();
  await expect(tab, `раздел «${section}» открыт`).toHaveAttribute('aria-selected', 'true');
}

/** Вкладки кабинета заказчика: дашборд и список проектов. */
export type CabinetTab = 'Дашборд' | 'Проекты';

/**
 * Открыть вкладку кабинета заказчика.
 *
 * Кабинет открывается дашбордом — так решил владелец продукта: заказчик
 * приходит с вопросом «как идут дела», а не «покажи список». Список
 * проектов теперь соседняя вкладка, и специи, которым нужен именно он,
 * обязаны его открыть.
 */
export async function openCabinetTab(page: Page, name: CabinetTab): Promise<void> {
  const tabs = page.locator('.tabs[role="tablist"]').first();
  await expect(tabs, 'полоса вкладок кабинета нарисована').toBeVisible({ timeout: 15_000 });
  const tab = tabs.getByRole('tab', { name }).first();
  await tab.click();
  await expect(tab, `вкладка «${name}» открыта`).toHaveAttribute('aria-selected', 'true');
}

