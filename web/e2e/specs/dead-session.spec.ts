import { test, expect } from '@playwright/test';
import { AUTH_KEY } from '../fixtures/world';

/**
 * Протухшая сессия: человеку говорят, что произошло.
 *
 * Самая тихая поломка из всех: приложение выглядело как упавший сервер.
 * Экраны пустели один за другим — каждый запрос отвечал отказом, —
 * сообщения не было, на вход не уводило, а негодная сессия так и лежала
 * в браузере, так что перезагрузка страницы ничего не меняла. Человек
 * писал «у вас всё сломалось», и это было честное описание увиденного.
 *
 * Причина была не в отказе, а в его обработке: запрос обновления токена
 * идёт через тот же перехватчик, и его собственный отказ снова запускал
 * обновление — подписку на тот самый запрос, который в эту секунду
 * падает. До ветки «сессия мертва» дело не доходило никогда.
 *
 * Поэтому проверяем не перехватчик, а три его обещания разом: сказать,
 * убрать негодную сессию и увести туда, где можно войти. Каждое по
 * отдельности ничего не стоит: сообщение без очистки человек прочтёт ещё
 * четыре раза, очистка без перехода оставит его на пустой странице.
 */

/** Токены, которые сервер не примет: подпись не сойдётся. */
const DEAD = {
  access_token: 'dead.access.token',
  refresh_token: 'dead.refresh.token',
};

test('негодная сессия говорит об этом, чистится и уводит на вход', async ({ context, page }) => {
  await context.addInitScript(
    ([key, session]) => window.localStorage.setItem(key as string, JSON.stringify(session)),
    [AUTH_KEY, DEAD] as const,
  );

  // Ждём разметку, а не полную загрузку: после выброса открывается
  // витрина с портфолио, и её картинки грузятся дольше, чем живёт
  // сообщение. С ожиданием `load` специя приходила к готовому экрану,
  // на котором сообщение уже погасло, — и «молчит» было не отличить от
  // «сказало и убрало».
  await page.goto('/me/projects', { waitUntil: 'domcontentloaded' });

  // Сказать. Без этого человек видит пустые экраны и думает на сервер.
  await expect(page.getByText(/Сессия истекла/)).toBeVisible({ timeout: 15_000 });

  // Убрать. Негодная сессия в хранилище значит, что перезагрузка страницы
  // повторит ровно то же самое, и выйти из этого нельзя.
  await expect
    .poll(() => page.evaluate((key) => window.localStorage.getItem(key), AUTH_KEY), {
      message: 'негодная сессия должна быть вычищена из браузера',
    })
    .toBeNull();

  // Увести. Отдельной страницы входа нет — вход живёт окном на главной,
  // и остаться на защищённой странице значит остаться там, где ни один
  // запрос не пройдёт.
  await expect(page).not.toHaveURL(/\/me\/projects/);
  await expect(page.getByRole('button', { name: 'Войти' }).first()).toBeVisible({
    timeout: 15_000,
  });
});

test('на публичной странице протухшая сессия не мешает смотреть витрину', async ({
  context,
  page,
}) => {
  await context.addInitScript(
    ([key, session]) => window.localStorage.setItem(key as string, JSON.stringify(session)),
    [AUTH_KEY, DEAD] as const,
  );

  // Витрина открыта всем, и уводить с неё некуда: человек уже там, где
  // входят. Переход на самого себя с параметром «вернуть на главную» —
  // это мигание страницы на ровном месте.
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('button', { name: 'Войти' }).first()).toBeVisible({
    timeout: 15_000,
  });
  await expect(page).toHaveURL(/localhost:4200\/$/);
});
